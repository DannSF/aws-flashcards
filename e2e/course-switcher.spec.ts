import { test, expect } from '@playwright/test';
test('one add action, searchable course switcher, keyboard dismissal and installed examples', async ({page}) => {
  await page.goto('/#courses');
  await expect(page.getByRole('button',{name:'Añadir curso',exact:true})).toHaveCount(1);
  await expect(page.getByRole('button',{name:'Importar curso',exact:true})).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Importar archivo',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Añadir curso',exact:true}).click();
  await page.getByLabel('Importar paquete JSON',{exact:true}).setInputFiles('public/packages/python-fundamentos.json');
  await page.getByRole('button',{name:'Añadir y abrir curso'}).click();
  const trigger = page.getByRole('button',{name:'Cambiar curso: Python desde cero',exact:true});
  await trigger.click();
  await expect(page.getByLabel('Buscar un curso para cambiar')).toBeFocused();
  await page.getByLabel('Buscar un curso para cambiar').fill('no-existe');
  await expect(page.getByRole('region',{name:'Cambiar de curso'})).toContainText('No hay coincidencias');
  await page.keyboard.press('Escape');
  await expect(trigger).toBeFocused(); await expect(trigger).toHaveAttribute('aria-expanded','false');
  await trigger.click();
  await page.getByLabel('Buscar un curso para cambiar').fill('aws');
  await expect(page.locator('.course-switch-list > button')).toHaveCount(1);
  await page.keyboard.press('Tab'); await page.keyboard.press('Enter');
  await expect(page.getByRole('button',{name:'Cambiar curso: AWS Cloud Practitioner',exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button',{name:'Cambiar curso: AWS Cloud Practitioner',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Mis cursos',exact:true}).click();
  await page.getByRole('button',{name:'Explorar ejemplos',exact:true}).click();
  await expect(page.getByRole('button',{name:'Vista previa de Python desde cero',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Abrir curso de Python desde cero',exact:true}).click();
  await expect(page.getByRole('button',{name:'Cambiar curso: Python desde cero',exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Abrir navegación'}).click();
  await page.getByRole('button',{name:'Cambiar curso: Python desde cero',exact:true}).click();
  await page.getByRole('button',{name:'Cambiar a AWS Cloud Practitioner',exact:true}).click();
  await expect.poll(() => page.locator('.sidebar').evaluate(el => el.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await page.getByRole('button',{name:'Abrir navegación'}).click();
  await page.getByRole('button',{name:'Cambiar curso: AWS Cloud Practitioner',exact:true}).click();
  await page.screenshot({path:'test-results/course-switcher-mobile.png'});
});
